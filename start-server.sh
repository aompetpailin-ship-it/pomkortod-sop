#!/bin/bash
# สคริปต์สำหรับรันระบบ SOP ร้านไก่ทอด "ผมขอทอด" อัตโนมัติ
cd "$(dirname "$0")"

IP_ADDR=$(ifconfig | grep "inet " | grep -v 127.0.0.1 | awk '{print $2}' | head -n 1)

echo "=========================================================="
echo "🍗 กำลังเริ่มเปิดระบบ SOP ร้านไก่ทอด 'ผมขอทอด'..."
echo "=========================================================="
echo "📍 เข้าใช้งานบนเครื่องนี้:  http://localhost:8080"
echo "🌐 เข้าใช้งานจากไอแพด/มือถือในร้าน (Wi-Fi): http://${IP_ADDR}:8080"
echo "=========================================================="
echo "กด Ctrl+C เมื่อต้องการปิดเซิร์ฟเวอร์"
echo "=========================================================="

# เปิด Web Browser อัตโนมัติ
open http://localhost:8080

# รัน Python HTTP Server บนพอร์ต 8080
python3 -m http.server 8080
